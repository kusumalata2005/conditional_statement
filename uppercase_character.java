package conditional_statement;

public class uppercase_character {

	public static void main(String[] args) {
		 
		char ch = 'M';
		if(ch >= 'A' && ch <= 'Z') {
			
			System.out.println("character is uppercase.....");
		}else {
			
			System.out.println("character is not uppercase.....");
		}
	}

}
